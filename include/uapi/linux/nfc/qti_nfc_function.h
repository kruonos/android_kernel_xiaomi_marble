struct qti_nfc_function_abi {
	__u16 abi_major;
	__u16 abi_minor;
	__u16 size;
	__u16 reserved0;
	__u32 capabilities;
	__u32 max_data_len;
	__u32 max_nci_frame_len;
	__u32 max_frame_len;
	__u32 max_timeout_ms;
	__u32 max_function_id;
	__u32 reserved[8];
};

struct qti_nfc_function_session {
	__u16 abi_major;
	__u16 abi_minor;
	__u16 size;
	__u16 reserved0;
	__u32 flags;
	__u32 default_timeout_ms;
	__u32 session_id;
	__u32 reserved[5];
};

struct qti_nfc_function_runtime_state {
	__u8 mode;
	__u8 controller_state;
	__u8 ven;
	__u8 firm;
	__u8 irq;
	__u8 clkreq;
	__u8 regulator_enabled;
	__u8 nfc_enabled;
	__u8 ese_powered;
	__u8 ese_state;
	__u8 rf_field;
	__u8 interface_type;
	__u8 chip_type;
	__u8 rom_version;
	__u8 fw_major;
	__u8 fw_minor;
};

struct qti_nfc_function_gpio_value {
	__u32 gpio;
	__s32 value;
};

struct qti_nfc_function_call {
	__u16 abi_major;
	__u16 abi_minor;
	__u16 size;
	__u16 reserved0;
	__u32 session_id;
	__u32 sequence;
	__u32 function;
	__u32 transport;
	__u32 flags;
	__s32 timeout_ms;
	__u32 request_len;
	__u32 response_capacity;
	__u32 response_len;
	__s32 status;
	__aligned_u64 timestamp_ns;
	__u8 request[QTI_NFC_FUNCTION_MAX_DATA];
	__u8 response[QTI_NFC_FUNCTION_MAX_DATA];
};

enum qti_nfc_function_record_type {
	QTI_NFC_FUNCTION_RECORD_SESSION_START = 1,
	QTI_NFC_FUNCTION_RECORD_CALL = 2,
	QTI_NFC_FUNCTION_RECORD_RESULT = 3,
	QTI_NFC_FUNCTION_RECORD_EVENT = 4,
	QTI_NFC_FUNCTION_RECORD_ERROR = 5,
	QTI_NFC_FUNCTION_RECORD_SESSION_END = 6,
};

/* Little-endian persistent/streaming record header used by userspace tools. */
struct qti_nfc_function_record_header {
	__le32 magic;
	__le16 version;
	__le16 header_len;
	__le32 type;
	__le32 flags;
	__le32 session_id;
	__le32 sequence;
	__le32 function;
	__le32 transport;
	__le32 payload_len;
	__le32 status;
	__le32 timeout_ms;
	__le32 reserved0;
	__le64 timestamp_ns;
} __attribute__((__packed__));

