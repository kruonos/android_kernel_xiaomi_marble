#define QTI_NFC_FUNCTION_SESSION_CLOSE \
	_IOW(QTI_NFC_FUNCTION_IOC_MAGIC, 0x02, struct qti_nfc_function_session)
#define QTI_NFC_FUNCTION_CALL \
	_IOWR(QTI_NFC_FUNCTION_IOC_MAGIC, 0x03, struct qti_nfc_function_call)

